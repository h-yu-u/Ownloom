"""Retrieval and credential boundaries."""

from typing import Protocol

from mlx_studio_runtime.domain.web import PageRead, SearchHit, WebConfig


class SecretStore(Protocol):
    def put(self, value: str) -> str: ...
    def resolve(self, reference: str) -> str: ...
    def delete(self, reference: str) -> None: ...


class WebConfigStore(Protocol):
    def current(self) -> WebConfig | None: ...
    def get(self, config_id: str, revision: int) -> WebConfig: ...
    def save(self, expected_revision: int, base_url: str, secret_ref: str | None) -> WebConfig: ...
    def bind_job(self, job_id: str, config: WebConfig) -> None: ...
    def tested(self, config_id: str, revision: int) -> bool: ...
    def mark_tested(self, config_id: str, revision: int) -> None: ...


class SearchProvider(Protocol):
    async def search(self, query: str, config: WebConfig, credential: str) -> list[SearchHit]: ...


class PageReader(Protocol):
    async def read(self, urls: list[str], config: WebConfig, credential: str) -> list[PageRead]: ...


class ResultPolicy(Protocol):
    async def allowed(self, url: str) -> bool: ...
