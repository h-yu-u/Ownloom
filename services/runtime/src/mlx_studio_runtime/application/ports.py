"""Narrow contracts implemented by storage, transport and filesystem adapters."""

import asyncio
from collections.abc import AsyncIterator, Awaitable, Callable
from contextlib import AbstractContextManager
from pathlib import Path
from typing import Any, Protocol, TypeVar

from mlx_studio_runtime.domain.generation_stats import GenerationStats
from mlx_studio_runtime.domain.jobs import Job, JobEvent

T = TypeVar("T")
R = TypeVar("R")


class EventPublisher(Protocol):
    async def publish(self, event_type: str, payload: dict[str, Any]) -> object: ...


class ModelRepository(Protocol):
    def list(self) -> list[dict[str, Any]]: ...
    def upsert(self, manifest: dict[str, Any], state: str = "available") -> None: ...
    def update_state(self, model_id: str, state: str) -> None: ...
    def remove(self, model_id: str) -> bool: ...


class JobRepository(Protocol):
    def save_result(self, job_id: str, result: dict[str, Any]) -> None: ...

    def get(self, job_id: str) -> dict[str, Any] | None: ...
    def save(self, item: dict[str, Any]) -> None: ...
    def update(self, job_id: str, state: str, error_code: str | None = None) -> None: ...
    def task_summaries(self) -> list[dict[str, Any]]: ...
    def list(self) -> list[dict[str, Any]]: ...
    def recover_interrupted(self, error_code: str) -> int: ...
    def set_phase(self, job_id: str, phase: str) -> int: ...


class ConversationRepository(Protocol):
    def handoff_messages(
        self, conversation_id: str, identifiers: list[str]
    ) -> list[dict[str, Any]]: ...
    def page(
        self, conversation_id: str, before: str | None = None, limit: int = 50
    ) -> dict[str, Any] | None: ...
    def get(self, conversation_id: str) -> dict[str, Any] | None: ...
    def list(self) -> list[dict[str, Any]]: ...
    def save(self, item: dict[str, Any]) -> None: ...
    def rename(self, conversation_id: str, title: str) -> bool: ...
    def update_metadata(
        self,
        conversation_id: str,
        title: str | None,
        pinned: bool | None,
        web_search_enabled: bool | None = None,
    ) -> bool: ...
    def delete(self, conversation_id: str) -> bool: ...
    def save_message(self, item: dict[str, Any], replace_message_id: str | None = None) -> None: ...


class AttachmentReader(Protocol):
    def get_many(self, attachment_ids: list[str]) -> list[dict[str, Any]] | None: ...


class ImageRepository(Protocol):
    def find_submission(self, request_id: str) -> tuple[str, str] | None: ...
    def jobs(self, job_id: str | None = None) -> list[dict[str, Any]]: ...
    def list_artifacts(self, limit: int, offset: int) -> list[dict[str, Any]]: ...
    def get(self, artifact_id: str) -> dict[str, Any] | None: ...
    def save(
        self, artifact_id: str, job_id: str, relative_path: str, metadata: dict[str, object]
    ) -> None: ...


class InferenceWorker(Protocol):
    @property
    def pid(self) -> int | None: ...
    async def load(self, manifest: dict[str, Any]) -> None: ...
    def generate(
        self,
        job_id: str,
        prompt: str,
        max_tokens: int | None,
        temperature: float,
        image_paths: list[str],
        messages: list[dict[str, str]],
    ) -> AsyncIterator[dict[str, Any]]: ...
    def infer(self, job_id: str, request: dict[str, object]) -> AsyncIterator[dict[str, Any]]: ...
    def generate_image(
        self, job_id: str, parameters: dict[str, object], output_path: Path
    ) -> AsyncIterator[dict[str, Any]]: ...
    def generate_audio(
        self, job_id: str, parameters: dict[str, object], output_path: Path
    ) -> AsyncIterator[dict[str, Any]]: ...
    async def cancel(self, job_id: str) -> None: ...
    async def stop(self) -> None: ...


Transaction = Callable[[], AbstractContextManager[object]]


class SubmissionJournal(Protocol):
    def find(self, conversation_id: str, request_id: str) -> tuple[str, str, int] | None: ...
    def save(self, conversation_id: str, request_id: str, digest: str, job_id: str) -> None: ...


class JobWriter(Protocol):
    def output_text(self, job_id: str) -> str: ...
    def text_revision(self, job_id: str) -> int: ...
    def save_result(self, job_id: str, result: dict[str, Any]) -> None: ...
    def get(self, job_id: str) -> Job: ...
    def cancellation_requested(self, job_id: str) -> bool: ...
    async def register(
        self, job: "Job", request: dict[str, object], persist: Callable[[], None] | None = None
    ) -> None: ...
    async def transition(self, job_id: str, event: "JobEvent") -> "Job": ...
    async def finish(
        self,
        job_id: str,
        event: "JobEvent",
        error_code: str | None = None,
        persist: Callable[[], None] | None = None,
        finish_reason: str | None = None,
    ) -> "Job": ...
    async def finish_failed_or_cancelled(self, job_id: str, error_code: str) -> "Job": ...
    def append_output(
        self, job_id: str, text: str, generation_stats: GenerationStats | None = None
    ) -> None: ...
    async def set_phase(self, job_id: str, phase: str) -> None: ...


class JobAdmission(Protocol):
    @property
    def lifecycle(self) -> JobWriter: ...
    def check_admission(self, model_id: str) -> None: ...
    def schedule(self, job: Job, execute: Callable[[], Awaitable[None]]) -> asyncio.Task[None]: ...
    async def cancel(self, job_id: str) -> dict[str, str]: ...
    def schedule_prepared(
        self,
        job: Job,
        prepare: Callable[[], Awaitable[T]],
        execute: Callable[[T], Awaitable[R]],
        finalize: Callable[[R, T], Awaitable[None]],
    ) -> asyncio.Task[None]: ...


class TextInference(Protocol):
    @property
    def events(self) -> EventPublisher: ...
    def generate(
        self,
        job_id: str,
        prompt: str,
        max_tokens: int | None,
        temperature: float,
        image_paths: list[str],
        messages: list[dict[str, str]],
    ) -> AsyncIterator[dict[str, Any]]: ...


class ImageInference(Protocol):
    @property
    def events(self) -> EventPublisher: ...
    def generate_image(
        self, job_id: str, parameters: dict[str, object], output_path: Path
    ) -> AsyncIterator[dict[str, Any]]: ...


class SpeechInference(Protocol):
    @property
    def events(self) -> EventPublisher: ...
    def generate_audio(
        self, job_id: str, parameters: dict[str, object], output_path: Path
    ) -> AsyncIterator[dict[str, Any]]: ...


class StructuredInference(Protocol):
    def infer(self, job_id: str, request: dict[str, object]) -> AsyncIterator[dict[str, Any]]: ...
