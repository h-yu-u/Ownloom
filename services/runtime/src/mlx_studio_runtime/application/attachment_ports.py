"""Narrow preparation boundaries. Children never receive repository connections."""

from collections.abc import AsyncIterator
from pathlib import Path
from typing import Any, Protocol


class OriginalStorage(Protocol):
    async def upload(
        self,
        chunks: AsyncIterator[bytes],
        filename: str,
        client_upload_id: str | None = None,
        draft_id: str | None = None,
        draft_revision: int | None = None,
    ) -> dict[str, Any]: ...
    def read(self, attachment_id: str) -> tuple[Path, dict[str, Any]]: ...


class PreparationStore(Protocol):
    def latest(self, attachment_id: str) -> dict[str, Any] | None: ...
    def get(self, attachment_id: str, preparation_id: str) -> dict[str, Any]: ...
    def create(self, item: dict[str, Any]) -> dict[str, Any]: ...
    def claim(self, attachment_id: str, preparation_id: str, owner: str) -> bool: ...
    def commit(self, preparation_id: str, owner: str, manifest: dict[str, Any]) -> bool: ...


class PreparationRunner(Protocol):
    async def run(self, source: Path, staging: Path, format_name: str) -> dict[str, Any]: ...


class DerivedStorage(Protocol):
    def staging(self, preparation_id: str, owner: str) -> Path: ...
    def publish(self, staging: Path, preparation_id: str) -> None: ...
    def discard(self, staging: Path) -> None: ...
    def remove(self, preparation_id: str) -> None: ...
    def file(self, preparation_id: str, name: str, sha256: str) -> Path: ...
    def blocks(self, preparation: dict[str, Any]) -> list[dict[str, Any]]: ...
