"""Generate both process contracts from the one internal JSON schema."""

import argparse
import json
import pprint
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]


def ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"({ts_type(schema['items'])})[]"
    if kind == "object":
        fields = schema.get("properties", {})
        if not fields:
            additional = schema.get("additionalProperties")
            value = ts_type(additional) if isinstance(additional, dict) else "unknown"
            return f"Record<string, {value}>"
        required = schema.get("required", [])
        return (
            "{ "
            + "; ".join(
                f"{json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)}"
                for name, value in fields.items()
            )
            + " }"
        )
    return {
        "integer": "number",
        "number": "number",
        "string": "string",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def python_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return "Literal[" + ", ".join(repr(value) for value in schema["enum"]) + "]"
    if "anyOf" in schema:
        return " | ".join(python_type(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"list[{python_type(schema['items'])}]"
    if kind == "object":
        additional = schema.get("additionalProperties")
        value = python_type(additional) if isinstance(additional, dict) else "Any"
        return f"dict[str, {value}]"
    return {
        "integer": "int",
        "number": "float",
        "string": "str",
        "boolean": "bool",
        "null": "None",
    }.get(kind, "Any")


def extension_models(schema: dict[str, Any]) -> str:
    lines = [
        "# fmt: off",
        "# ruff: noqa",
        '"""Generated from the Host schema; do not edit."""',
        "from __future__ import annotations",
        "from typing import Any, Literal",
        "from pydantic import BaseModel, ConfigDict, Field",
        "",
    ]
    models: list[str] = []
    for name, definition in schema["$defs"].items():
        if not name.startswith(("Extension", "Mcp", "Skill")):
            continue
        if definition.get("type") != "object" or not definition.get("properties"):
            lines.append(f"{name} = {python_type(definition)}")
            continue
        models.append(name)
        lines += [
            f"class {name}(BaseModel):",
            '    model_config = ConfigDict(extra="forbid")',
        ]
        for field, rule in definition["properties"].items():
            optional = field not in definition.get("required", [])
            annotation = python_type(rule) + (" | None" if optional else "")
            constraints = {
                "minLength": "min_length",
                "maxLength": "max_length",
                "maxItems": "max_length",
                "minimum": "ge",
                "maximum": "le",
                "pattern": "pattern",
            }
            args = ["default=None"] if optional else []
            args += [
                f"{target}={rule[key]!r}"
                for key, target in constraints.items()
                if key in rule
            ]
            default = " = Field(" + ", ".join(args) + ")" if args else ""
            lines.append(f"    {field}: {annotation}{default}")
        lines.append("")
    lines += [f"{model}.model_rebuild()" for model in models]
    return "\n".join(lines) + "\n"


def outputs(schema: dict[str, Any], root: Path) -> dict[Path, str]:
    methods = schema["methods"]
    declarations = [
        "// Generated by scripts/generate/generate_coding_rpc.py; edit the schema."
    ]
    for name, definition in schema["$defs"].items():
        declarations.append(f"export type {name} = {ts_type(definition)}")
    for kind in ["params", "result"]:
        declarations.append(f"export interface Rpc{kind.title()}Map {{")
        for method, spec in methods.items():
            declarations.append(f"  {json.dumps(method)}: {ts_type(spec[kind])}")
        declarations.append("}")
    declarations += ["export type RpcMethod = keyof RpcParamsMap"]
    limits = schema["$defs"]["CodingSettings"]["properties"]
    return {
        root
        / "packages/api-client/src/coding-limits.ts": "// Generated by scripts/generate/generate_coding_rpc.py; edit the schema.\n"
        + "export const codingLimits = {\n"
        + "".join(
            f"  {key}: {{ minimum: {rule['minimum']}, maximum: {rule['maximum']} }},\n"
            for key, rule in limits.items()
            if "maximum" in rule
        )
        + "} as const\n",
        root
        / "services/runtime/src/mlx_studio_runtime/entrypoints/http/extension_models.py": extension_models(
            schema
        ),
        root
        / "services/coding-agent/src/protocol/generated/schema.ts": "// Generated; edit packages/coding-protocol/schema.json.\nexport const rpcSchema = "
        + json.dumps(schema, ensure_ascii=False, indent=2)
        + " as const\n",
        root / "services/coding-agent/src/protocol/generated/types.d.ts": "\n".join(
            declarations
        )
        + "\n",
        root
        / "services/runtime/src/mlx_studio_runtime/domain/generated/coding_rpc.py": '"""Generated by scripts/generate/generate_coding_rpc.py; do not edit."""\n\nfrom typing import Any, Literal\n\nRpcMethod = Literal[\n'
        + "".join(f"    {method!r},\n" for method in methods)
        + "]\n\nSCHEMA: dict[str, Any] = "
        + pprint.pformat(schema, width=95, sort_dicts=False)
        + "\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    schema = json.loads((ROOT / "packages/coding-protocol/schema.json").read_text())
    for path, content in outputs(schema, ROOT).items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(
                    f"Generated RPC contract drift: {path.relative_to(ROOT)}"
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
