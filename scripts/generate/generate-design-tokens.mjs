import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { format } from 'prettier'
const directory = new URL('../../apps/desktop/src/shared/styles/', import.meta.url)
const tokens = JSON.parse(await readFile(new URL('theme.tokens.json', directory), 'utf8'))
const schema = {
  surface: ['body', 'shell', 'sidebar', 'card', 'overlay', 'hover'],
  text: ['primary', 'secondary', 'tertiary'],
  action: ['primary', 'hover', 'pressed', 'onPrimary'],
  border: ['subtle', 'strong', 'focus'],
  status: ['success', 'warning', 'error', 'info'],
  space: ['1', '2', '3', '4', '6', '8'],
  radius: ['control', 'panel', 'overlay'],
  controlHeight: ['small', 'medium', 'large'],
  fontSize: ['caption', 'ui', 'body', 'section', 'title'],
}
const lengths = new Set(['space', 'radius', 'controlHeight', 'fontSize'])
const kebab = (value) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)
const lines = []
const ordered = {}
if (Object.keys(tokens).some((key) => !(key in schema))) throw new Error('Unknown token group')
for (const [group, keys] of Object.entries(schema)) {
  const values = tokens[group]
  if (!values || Object.keys(values).some((key) => !keys.includes(key)))
    throw new Error(`Invalid token group: ${group}`)
  ordered[group] = {}
  for (const key of keys) {
    const value = values[key]
    if (
      lengths.has(group)
        ? typeof value !== 'number' || !Number.isFinite(value) || value <= 0
        : typeof value !== 'string' || !/^#[0-9a-f]{6}$/i.test(value)
    )
      throw new Error(`Invalid token: ${group}.${key}`)
    ordered[group][key] = value
    lines.push(`  --${kebab(group)}-${kebab(key)}: ${value}${lengths.has(group) ? 'px' : ''};`)
  }
}
const outputs = [
  [
    'tokens.generated.css',
    `/* Generated by scripts/generate/generate-design-tokens.mjs. */\n:root {\n${lines.join('\n')}\n}\n`,
    'css',
  ],
  [
    'token-values.generated.ts',
    `// Generated by scripts/generate/generate-design-tokens.mjs.\nexport const designTokens = ${JSON.stringify(ordered, null, 2)} as const\n`,
    'typescript',
  ],
]
for (const [name, source, parser] of outputs) {
  const expected = await format(source, {
    parser,
    singleQuote: true,
    semi: false,
    trailingComma: 'all',
    printWidth: 100,
  })
  const path = new URL(name, directory)
  if (process.argv.includes('--check')) {
    const actual = await readFile(path, 'utf8').catch(() => '')
    if (actual !== expected) {
      process.stderr.write(`Design token drift: ${fileURLToPath(path)}\n`)
      process.exitCode = 1
    }
  } else await writeFile(path, expected)
}
